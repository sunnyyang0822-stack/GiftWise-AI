TAGS_VALID = ("alcohol", "food", "fragrance", "jewelry", "plant", "other")


def cand(cid, name, desc, total, days, tags, reason, refs=None, inf=None, unk=None, currency="CNY"):
    """按契约构造一个候选（11 个必填字段齐全）。"""
    return {
        "id": cid,
        "name": name,
        "description": desc,
        "estimated_total": total,
        "currency": currency,
        "estimated_preparation_days": days,
        "tags": list(tags),
        "reason": reason,
        "fact_refs": list(refs or []),
        "inferences": list(inf or []),
        "unknowns": list(unk or []),
    }


UNK_STD = ["实际价格、库存与送达均未核实；估算含基础包装、贺卡与配送"]


def batch(*cands):
    return {"candidates": list(cands)}


# ---------------------------------------------------------------- 基础 intake
def intake(relation, closeness, occasion, budget, days, interests=None,
           confidence=None, styles=None, tags=None, terms=None,
           unresolved=None, context=""):
    return {
        "recipient_relation": relation,
        "closeness": closeness,
        "occasion": occasion,
        "budget_amount": budget,
        "currency": "CNY",
        "deadline_days": days,
        "interests": list(interests or []),
        "interest_confidence": dict(confidence or {}),
        "gift_styles": list(styles or []),
        "hard_exclusions": {
            "tags": list(tags or []),
            "terms": list(terms or []),
            "unresolved": list(unresolved or []),
        },
        "additional_context": context,
    }


